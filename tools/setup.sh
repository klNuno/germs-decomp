#!/usr/bin/env bash
# Licence: MIT for the code written for this project only; game-derived data and Sony names in it are excluded (LICENSING.md).
# Install the pinned decomp toolchain into tools/ and .venv/. Safe to re-run.
#   tools/setup.sh          install, verified against tools/toolchain.sha256 and tools/requirements.lock
#   tools/setup.sh --lock   rewrite both lock files first (only when bumping tools/versions.env)
set -euo pipefail
cd "$(dirname "$0")/.."
T=tools
LOCK=0
if [ "${1:-}" = "--lock" ]; then LOCK=1; fi
# shellcheck source=versions.env
. "$T/versions.env"
mkdir -p "$T/dl" "$T/bin" "$T/src" "$T/gcc"

gh_asset() { # owner/repo tag asset
  local f="$T/dl/$3"
  if [ ! -f "$f" ]; then
    curl -fsSL --retry 3 -o "$f.part" "https://github.com/$1/releases/download/$2/$3"
    mv "$f.part" "$f"
  fi
}

git_pin() { # url rev name
  local d="$T/src/$3"
  if [ ! -d "$d/.git" ]; then git clone -q "$1" "$d"; fi
  if ! git -C "$d" cat-file -e "$2^{commit}" 2>/dev/null; then git -C "$d" fetch -q origin; fi
  git -C "$d" -c advice.detachedHead=false checkout -q "$2"
}


# Release binaries, checked by sha256
MKPSXISO_ZIP="mkpsxiso-${MKPSXISO_TAG#v}-Linux.zip"
for v in $OLD_GCC_VERSIONS; do gh_asset decompals/old-gcc "$OLD_GCC_TAG" "gcc-$v.tar.gz"; done
gh_asset Lameguy64/mkpsxiso "$MKPSXISO_TAG" "$MKPSXISO_ZIP"
gh_asset encounter/objdiff "$OBJDIFF_TAG" objdiff-cli-linux-x86_64
# PCSX-Redux only ships rolling dev builds; an old one can vanish from distrib.app.
PCSX_ZIP="PCSX-Redux-$PCSX_REDUX_REV-linux-x86_64.zip"
if [ ! -f "$T/dl/$PCSX_ZIP" ]; then
  curl -fsSL --retry 3 -o "$T/dl/$PCSX_ZIP.part" "https://distrib.app$PCSX_REDUX_ASSET" \
    && mv "$T/dl/$PCSX_ZIP.part" "$T/dl/$PCSX_ZIP" \
    || { rm -f "$T/dl/$PCSX_ZIP.part"; echo "warning: $PCSX_ZIP is gone from distrib.app; the build does not need it, in-game checks do (put a saved copy in $T/dl/ and re-run)"; }
fi
if [ $LOCK = 1 ]; then
  # a lock written without the emulator zip would drop its hash and let any later copy through unchecked
  [ -f "$T/dl/$PCSX_ZIP" ] || { echo "--lock needs $T/dl/$PCSX_ZIP"; exit 1; }
  sha256sum "$T"/dl/* > "$T/toolchain.sha256"
fi
# --ignore-missing: only PCSX-Redux may be absent here (every other download above stops the script when it fails)
sha256sum -c --quiet --ignore-missing "$T/toolchain.sha256"

# MIPS binutils: the system ones when installed, else Debian's package unpacked into tools/binutils.
# tools/bin/mipsel-linux-gnu-* always exist, so the Makefile and the tools call one path.
BU_TOOLS="as ld objcopy objdump nm readelf"
if command -v mipsel-linux-gnu-as >/dev/null; then
  for b in $BU_TOOLS; do ln -sf "$(command -v mipsel-linux-gnu-$b)" "$T/bin/mipsel-linux-gnu-$b"; done
else
  if [ ! -f "$T/dl/$BINUTILS_DEB" ]; then
    curl -fsSL --retry 3 -o "$T/dl/$BINUTILS_DEB.part" "$BINUTILS_URL/$BINUTILS_DEB" && mv "$T/dl/$BINUTILS_DEB.part" "$T/dl/$BINUTILS_DEB" \
      || { rm -f "$T/dl/$BINUTILS_DEB.part"; echo "missing binutils: apt install binutils-mipsel-linux-gnu, or put $BINUTILS_DEB in $T/dl/"; exit 1; }
    sha256sum -c --quiet --ignore-missing "$T/toolchain.sha256"
  fi
  if [ ! -x "$T/binutils/usr/bin/mipsel-linux-gnu-as" ]; then
    rm -rf "$T/binutils"; mkdir -p "$T/binutils"
    (cd "$T/binutils" && ar x "../dl/$BINUTILS_DEB" && tar -xf data.tar.* && rm -f data.tar.* control.tar.* debian-binary)
  fi
  for b in $BU_TOOLS; do
    cat > "$T/bin/mipsel-linux-gnu-$b" <<WRAP
#!/bin/sh
# generated by tools/setup.sh: Debian's cross binutils with their private libraries
d="\$(cd "\$(dirname "\$0")/../binutils/usr" && pwd)"
LD_LIBRARY_PATH="\$d/lib/x86_64-linux-gnu\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}" exec "\$d/bin/mipsel-linux-gnu-$b" "\$@"
WRAP
    chmod +x "$T/bin/mipsel-linux-gnu-$b"
  done
fi

for v in $OLD_GCC_VERSIONS; do
  d="$T/gcc/$v"
  if [ ! -x "$d/cc1" ]; then mkdir -p "$d"; tar -xzf "$T/dl/gcc-$v.tar.gz" -C "$d"; fi
done
if [ ! -x "$T/bin/dumpsxiso" ]; then
  python3 -c 'import sys, zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])' "$T/dl/$MKPSXISO_ZIP" "$T/src"
  mk="$T/src/${MKPSXISO_ZIP%.zip}/bin"
  install -m 755 "$mk/dumpsxiso" "$mk/mkpsxiso" "$T/bin/"
fi
install -m 755 "$T/dl/objdiff-cli-linux-x86_64" "$T/bin/objdiff-cli"
if [ ! -x "$T/src/pcsx-redux/AppRun" ] && [ -f "$T/dl/$PCSX_ZIP" ]; then
  # No FUSE in containers: unpack the AppImage instead of mounting it.
  tmp=$(mktemp -d)
  python3 -c 'import sys, zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])' "$T/dl/$PCSX_ZIP" "$tmp"
  chmod +x "$tmp"/*.AppImage
  (cd "$tmp" && ./*.AppImage --appimage-extract >/dev/null)
  rm -rf "$T/src/pcsx-redux"
  mv "$tmp/squashfs-root" "$T/src/pcsx-redux"
  rm -rf "$tmp"
fi

# Source tools, pinned by commit
git_pin https://github.com/mkst/maspsx "$MASPSX_REV" maspsx
git_pin https://github.com/matt-kempster/m2c "$M2C_REV" m2c
git_pin https://github.com/simonlindholm/decomp-permuter "$PERMUTER_REV" decomp-permuter
git_pin https://github.com/simonlindholm/asm-differ "$ASM_DIFFER_REV" asm-differ
git_pin https://github.com/lab313ru/psx_psyq_signatures "$PSYQ_SIGNATURES_REV" psx_psyq_signatures

if [ ! -x "$T/bin/mipsmatch" ]; then
  cargo install -q --locked --git https://github.com/ttkb-oss/mipsmatch --rev "$MIPSMATCH_REV" --root "$T/mipsmatch" --jobs 3
  ln -sf ../mipsmatch/bin/mipsmatch "$T/bin/mipsmatch"
fi

# Python: splat and the helpers of m2c, permuter and asm-differ
# a venv whose python3 was upgraded under it points at an interpreter without its packages: rebuild it
if [ -e .venv ] && ! .venv/bin/python -c 'import os, sys; sys.exit(not os.path.isdir(os.path.join(sys.prefix, "lib", "python%d.%d" % sys.version_info[:2])))' 2>/dev/null; then
  echo "setup: .venv belongs to another python3, rebuilding it"; rm -rf .venv
fi
# uv when available: its venv has no pip, and it fetches PYTHON_VERSION when the system python3 is newer
if command -v uv >/dev/null; then
  if [ ! -x .venv/bin/python ]; then uv venv -q --python "$PYTHON_VERSION" .venv; fi
  PIP=(uv pip install -q --python .venv/bin/python)
else
  if [ ! -x .venv/bin/python ]; then python3 -m venv .venv; fi
  PIP=(.venv/bin/pip install -q)
fi
if [ $LOCK = 1 ]; then
  "${PIP[@]}" -r "$T/requirements.in"
  if command -v uv >/dev/null; then uv pip freeze --python .venv/bin/python > "$T/requirements.lock"; else .venv/bin/pip freeze > "$T/requirements.lock"; fi
fi
"${PIP[@]}" -r "$T/requirements.lock"

echo "== toolchain"
"$T/bin/mipsel-linux-gnu-as" --version | head -1
for v in $OLD_GCC_VERSIONS; do printf '%s: ' "$v"; echo 'int f(void){return 0;}' | "$T/gcc/$v/cc1" -quiet -version -o /dev/null 2>&1 | head -1; done
"$T/bin/objdiff-cli" --version
"$T/bin/mipsmatch" --version 2>/dev/null || echo "mipsmatch $MIPSMATCH_REV"
if [ -x "$T/src/pcsx-redux/AppRun" ]; then printf 'pcsx-redux: '; "$T/src/pcsx-redux/AppRun" -cli -version | grep -m1 '"version"'; else echo "pcsx-redux: not installed (in-game checks only)"; fi
.venv/bin/python -c 'import importlib.metadata as m; print("splat64", m.version("splat64"), "spimdisasm", m.version("spimdisasm"))'
echo "setup ok"
